@dp.message(Command("grant"))
async def admin_grant_start(message: Message, state: FSMContext):
    if message.from_user.id != ADMIN_ID:
        await message.answer("У тебя нет прав администратора.")
        return
    await state.set_state(GrantState.waiting_user_id)
    await message.answer("Введи Telegram ID пользователя, которому выдать подписку:")

@dp.message(GrantState.waiting_user_id)
async def admin_grant_process(message: Message, state: FSMContext):
    try:
        user_id = int(message.text.strip())
    except ValueError:
        await message.answer("Это не число. Введи ID ещё раз.")
        return

    grant_subscription(user_id)
    await message.answer(f"✅ Подписка выдана пользователю {user_id}.")
    await state.clear()

    try:
        await bot.send_message(
            user_id,
            "🎉 Твоя подписка активирована! Все уроки теперь открыты. Удачи!"
        )
    except Exception:
        pass

