def split_text(text, limit=PART_LIMIT):
    """Разбивает длинный текст на части по ~limit символов."""
    # Разделяем на абзацы (по двум переносам строки)
    paragraphs = text.split("\n\n")
    parts = []
    current = ""

    for para in paragraphs:
        # Если абзац сам по себе длиннее лимита - режем его на куски
        if len(para) > limit:
            if current:
                parts.append(current.strip())
                current = ""
            # Режем длинный абзац
            while len(para) > limit:
                parts.append(para[:limit].strip())
                para = para[limit:]
            current = para
            continue

        # Если добавление абзаца превышает лимит - сохраняем текущую часть
        if current and len(current) + len(para) + 2 > limit:
            parts.append(current.strip())
            current = para
        else:
            if current:
                current += "\n\n" + para
            else:
                current = para

    if current.strip():
        parts.append(current.strip())

    return parts

