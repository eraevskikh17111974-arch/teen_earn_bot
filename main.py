DB_NAME = "teen_earn.db"

def get_conn():
    conn = sqlite3.connect(DB_NAME)
    conn.row_factory = sqlite3.Row
    return conn

def init_db():
    conn = get_conn()
    cur = conn.cursor()
    cur.execute("""
        CREATE TABLE IF NOT EXISTS users (
            user_id INTEGER PRIMARY KEY,
            username TEXT,
            name TEXT,
            has_subscription INTEGER DEFAULT 0,
            subscribed_at TEXT
        )
    """)
    cur.execute("""
        CREATE TABLE IF NOT EXISTS progress (
            user_id INTEGER,
            lesson_number INTEGER,
            PRIMARY KEY (user_id, lesson_number)
        )
    """)
    conn.commit()
    conn.close()

def add_user(user_id, username, name):
    conn = get_conn()
    conn.execute("""
        INSERT OR IGNORE INTO users (user_id, username, name)
        VALUES (?, ?, ?)
    """, (user_id, username, name))
    conn.commit()
    conn.close()

def get_user(user_id):
    conn = get_conn()
    u = conn.execute("SELECT * FROM users WHERE user_id=?", (user_id,)).fetchone()
    conn.close()
    return u

def grant_subscription(user_id):
    conn = get_conn()
    conn.execute("""
        UPDATE users SET has_subscription=1, subscribed_at=?
        WHERE user_id=?
    """, (datetime.now().isoformat(), user_id))
    conn.commit()
    conn.close()

def complete_lesson(user_id, n):
    conn = get_conn()
    conn.execute("""
        INSERT OR IGNORE INTO progress (user_id, lesson_number)
        VALUES (?, ?)
    """, (user_id, n))
    conn.commit()
    conn.close()

def get_completed(user_id):
    conn = get_conn()
    rows = conn.execute(
        "SELECT lesson_number FROM progress WHERE user_id=?", (user_id,)
    ).fetchall()
    conn.close()
    return [r["lesson_number"] for r in rows]

