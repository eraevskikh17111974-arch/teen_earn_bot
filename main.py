def part_nav_kb(lesson_idx, part_idx, total_parts):
    """Кнопки навигации по частям урока."""
    kb = InlineKeyboardMarkup(inline_keyboard=[])
    row = []
    if part_idx > 0:
        row.append(InlineKeyboardButton(text="⬅️ Назад", callback_data=f"lesson_{lesson_idx}_p{part_idx-1}"))
    if part_idx < total_parts - 1:
        row.append(InlineKeyboardButton(text="Дальше ➡️", callback_data=f"lesson_{lesson_idx}_p{part_idx+1}"))
    kb.inline_keyboard.append(row)

    if part_idx == total_parts - 1:
        # Последняя часть - кнопка завершения и следующий урок
        complete_row = []
        complete_row.append(InlineKeyboardButton(text="✅ Завершить урок", callback_data=f"lesson_{lesson_idx}_done"))
        kb.inline_keyboard.append(complete_row)
        if lesson_idx < len(LESSONS) - 1:
            next_row = [InlineKeyboardButton(text="➡️ Следующий урок", callback_data=f"lesson_{lesson_idx+1}")]
            kb.inline_keyboard.append(next_row)
    return kb

