def can_access_lesson(user, n):
    """Проверяет доступ к уроку: первый урок бесплатный или есть подписка."""
    if n == 1:
        return True
    return bool(user and user["has_subscription"])

@dp.callback_query(F.data.startswith("lesson_"))
async def open_lesson(callback: CallbackQuery):
    data = callback.data
    user = get_user(callback.from_user.id)

    # Парсим: lesson_3 или lesson_3_p2 или lesson_3_done
    parts = data.split("_")
    lesson_idx = int(parts[1])

    if not can_access_lesson(user, lesson_idx):
        await callback.message.answer(
            NO_SUB.format(price=SUBSCRIPTION_PRICE),
            reply_markup=pay_kb()
        )
        await callback.answer()
        return

    total_parts = len(LESSON_PARTS[lesson_idx - 1])
    part_idx = 0

    if len(parts) >= 4 and parts[3].startswith("p"):
        part_idx = int(parts[3][1:])
    elif len(parts) == 3 and parts[2] == "done":
        # Завершение урока
        complete_lesson(callback.from_user.id, lesson_idx)
        await callback.message.answer(
            f"🎉 Урок {lesson_idx} пройден! Ты молодец!"
        )
        await callback.answer()
        return

    lesson_title = LESSONS[lesson_idx - 1]["title"]
    text = LESSON_PARTS[lesson_idx - 1][part_idx]
    nav = part_nav_kb(lesson_idx, part_idx, total_parts)

    header = f"📖 {lesson_title}\n(Часть {part_idx+1} из {total_parts})\n\n"
    await callback.message.answer(header + text, reply_markup=nav)
    await callback.answer()

